import {
  CHIPS,
  MOODS,
  THEMES,
  TONES,
  themes,
  type Mood,
  type ThemeName,
  type ThemeTokens,
} from "./tokens";

/** Radial status wash over a vertical gradient. */
export function pageBg(t: ThemeTokens, mood: Mood): string {
  const n = t.page.stops.length - 1;
  const gradient = t.page.stops.map((c, i) => `${c} ${Math.round((i / n) * 100)}%`).join(", ");
  const [r, g, b, a] = t.page.wash[mood];
  return `radial-gradient(900px 540px at 50% -6%, rgba(${r},${g},${b},${a}), transparent 68%), linear-gradient(180deg, ${gradient})`;
}

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function declarations(t: ThemeTokens): string[] {
  const d: string[] = [];
  for (const k of [
    "canvas",
    "surface",
    "ink",
    "inkMuted",
    "hair",
    "track",
    "accent",
    "accentInk",
    "soft",
    "good",
    "warn",
    "bad",
  ] as const) {
    d.push(`--${kebab(k)}: ${t[k]};`);
  }
  for (const c of CHIPS)
    d.push(`--chip-${c}: ${t.chip[c][0]};`, `--chip-${c}-ink: ${t.chip[c][1]};`);
  for (const tone of TONES)
    d.push(
      `--ring-${tone}-from: ${t.ring[tone][0]};`,
      `--ring-${tone}-to: ${t.ring[tone][1]};`,
      `--glow-${tone}: ${t.glow[tone]};`,
    );
  for (const m of MOODS) d.push(`--page-bg-${m}: ${pageBg(t, m)};`);
  return d;
}

const block = (selector: string, t: ThemeTokens, scheme: "light" | "dark", indent = "") =>
  `${indent}${selector} {\n${indent}  color-scheme: ${scheme};\n${declarations(t)
    .map((l) => `${indent}  ${l}`)
    .join("\n")}\n${indent}}\n`;

const scheme = (n: ThemeName) => (n === "light" ? "light" : "dark");

/** The generated stylesheet: light by default, dark when the system asks (unless a theme is chosen), explicit themes by attribute. */
export function buildTokensCss(): string {
  let out = "/* GENERATED by `npm run tokens` from src/design/tokens.ts. Do not edit by hand. */\n";
  out += block(":root", themes.light, "light");
  out +=
    "\n@media (prefers-color-scheme: dark) {\n" +
    block(":root:not([data-theme])", themes.dark, "dark", "  ") +
    "}\n";
  for (const name of THEMES)
    out += "\n" + block(`:root[data-theme="${name}"]`, themes[name], scheme(name));
  return out;
}

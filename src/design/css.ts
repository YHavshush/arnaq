import { CHIPS, THEMES, TONES, themes, type ThemeName, type ThemeTokens } from "./tokens";

/** The page background: one gradient, the same on every screen. */
export function pageBg(t: ThemeTokens): string {
  const { angle, stops, at } = t.page;
  return `linear-gradient(${angle}deg, ${stops.map((c, i) => `${c} ${at[i]}%`).join(", ")})`;
}

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function declarations(t: ThemeTokens): string[] {
  const d: string[] = [];
  for (const k of [
    "canvas",
    "surface",
    "ink",
    "inkMuted",
    "hair",
    "track",
    "accent",
    "accentInk",
    "action",
    "actionInk",
    "select",
    "mark",
    "soft",
    "good",
    "warn",
    "bad",
  ] as const) {
    d.push(`--${kebab(k)}: ${t[k]};`);
  }
  for (const c of CHIPS)
    d.push(`--chip-${c}: ${t.chip[c][0]};`, `--chip-${c}-ink: ${t.chip[c][1]};`);
  for (const tone of TONES)
    d.push(
      `--ring-${tone}-from: ${t.ring[tone][0]};`,
      `--ring-${tone}-to: ${t.ring[tone][1]};`,
      `--glow-${tone}: ${t.glow[tone]};`,
    );
  d.push(
    `--glass-bg: ${t.glass.bg};`,
    `--glass-border: ${t.glass.border};`,
    `--glass-shadow: ${t.glass.shadow};`,
    `--glass-nav: ${t.glass.nav};`,
  );
  // The last stop is where the page ends; the onboarding fades its tints into it.
  d.push(`--page-bg: ${pageBg(t)};`, `--page-end: ${t.page.stops[t.page.stops.length - 1]};`);
  return d;
}

const block = (selector: string, name: ThemeName, scheme: "light" | "dark", indent = "") =>
  `${indent}${selector} {\n${indent}  color-scheme: ${scheme};\n${declarations(themes[name])
    .map((l) => `${indent}  ${l}`)
    .join("\n")}\n${indent}}\n`;

const scheme = (n: ThemeName) => (n === "light" ? "light" : "dark");

/** The generated stylesheet: light by default, dark when the system asks (unless a theme is chosen), explicit themes by attribute. */
export function buildTokensCss(): string {
  let out = "/* GENERATED by `npm run tokens` from src/design/tokens.ts. Do not edit by hand. */\n";
  out += block(":root", "light", "light");
  out +=
    "\n@media (prefers-color-scheme: dark) {\n" +
    block(":root:not([data-theme])", "dark", "dark", "  ") +
    "}\n";
  for (const name of THEMES) out += "\n" + block(`:root[data-theme="${name}"]`, name, scheme(name));
  return out;
}

const padded = (s: string) =>
  ` ${normaliseCounterparty(s)
    .replace(/[^a-z0-9.&'-]+/g, " ")
    .trim()} `;

const ENTRIES: { phrase: string; slug: string | null }[] = [
  ...Object.entries(CATALOG_NL).flatMap(([slug, phrases]) =>
    phrases.map((phrase) => ({ phrase: padded(phrase), slug })),
  ),
  ...AMBIGUOUS_NL.map((phrase) => ({ phrase: padded(phrase), slug: null })),
];

/**
 * The category slug a payment belongs to, from the name and description alone, or null when the
 * catalog has no unambiguous answer. The longest phrase wins ("uber eats" beats "uber"); an ambiguous
 * name that is at least as long as the best match cancels it.
 */
export function catalogLookup(
  counterparty: string | null,
  description: string | null,
): string | null {
  const text = padded(`${counterparty ?? ""} ${description ?? ""}`);
  let best: { length: number; slug: string | null } | null = null;
  for (const e of ENTRIES) {
    if (!text.includes(e.phrase)) continue;
    if (
      best === null ||
      e.phrase.length > best.length ||
      (e.phrase.length === best.length && e.slug === null)
    )
      best = { length: e.phrase.length, slug: e.slug };
  }
  return best?.slug ?? null;
}
